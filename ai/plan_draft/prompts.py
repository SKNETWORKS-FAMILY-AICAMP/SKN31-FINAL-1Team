def _payload(structured: dict) -> dict:
    reqs = structured.get("requirements") or {}
    return {
        "project": structured.get("project"),
        "users": structured.get("users") or [],
        "requirements": {
            "functional": reqs.get("functional") or [],
            "non_functional": reqs.get("non_functional") or [],
            "technical": reqs.get("technical") or [],
        },
        "decisions": [d for d in (structured.get("decisions") or [])
                      if d.get("category") in ("feature", "scope", "tech")],
        "constraints": structured.get("constraints") or [],
        "unresolved": structured.get("unresolved") or [],
    }

def build_messages(structured: dict) -> list[dict]:
    return [{"role": "user", "content": json.dumps(_payload(structured), ensure_ascii=False, indent=2)}]

